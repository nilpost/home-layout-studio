import assert from 'node:assert/strict';
import '../src/geometry.js';
const G=globalThis.LayoutGeometry;
const wall=(id,a,b)=>({id,kind:'wall',a,b});
const square=G.linearPath('M0 0H100V100H0Z','room','wall');
const scale={drawingUnits:100,realMillimetres:1000};
const codes=m=>G.validate({calibration:scale,...m}).issues.map(i=>i.code);
assert.deepEqual(codes({segments:square}),[],'closed boundary');
assert(codes({segments:square.slice(1)}).includes('open-wall-end'),'missing wall');
assert(codes({segments:[...square,wall('duplicate',[10,0],[90,0])]}).includes('duplicate-wall-span'));
assert(codes({segments:[wall('a',[0,0],[100,100]),wall('b',[0,100],[100,0])]}).includes('wall-crossing'));
assert(codes({segments:[wall('w',[0,0],[100,0]),{id:'glass',kind:'window',a:[20,0],b:[40,0]}]}).includes('wall-through-window'));
assert(codes({segments:square,fixtures:[{id:'fixed',x:40,y:-10,w:20,h:20}]}).includes('wall-through-fixture'));
assert(!codes({segments:square,fixtures:[{id:'fixed',x:10,y:10,w:20,h:20}]}).includes('wall-through-fixture'));
const opening=[wall('left',[0,0],[40,0]),{id:'door',kind:'opening',a:[40,0],b:[60,0]},wall('right',[60,0],[100,0]),...square.slice(1)];
assert.deepEqual(codes({segments:opening}),[],'opening bridges wall gap');
assert(codes({segments:[...square,{id:'door',kind:'opening',a:[40,0],b:[60,0]}]}).includes('wall-through-opening'));
assert(codes({segments:[{id:'door',kind:'opening',a:[10,10],b:[20,10]}]}).includes('unjoined-opening'));
assert(codes({segments:square,calibration:null}).includes('scale-unverified'));
assert(codes({segments:square,calibration:{drawingUnits:-1,realMillimetres:100}}).includes('scale-unverified'));
assert.deepEqual(G.linearPath('m0 0h100v100h-100z','room','wall').map(s=>[s.a,s.b]),square.map(s=>[s.a,s.b]));
assert.throws(()=>G.linearPath('M0 0A10 10 0 0 0 50 50','curve','wall'));
assert.throws(()=>G.linearPath('M0','bad','wall'));
console.log('PASS: 15 geometry checks (closed boundaries, gaps, duplicates, crossings, windows, doors, fixtures, calibration and unsupported paths).');
const dimension={id:'synthetic-dim',a:[0,0],b:[100,0],value:1000,unit:'mm',unitStatus:'verified'};
assert(!codes({segments:square,dimensions:[dimension]}).includes('dimension-scale-mismatch'));
assert(codes({segments:square,dimensions:[{...dimension,value:900}]}).includes('dimension-scale-mismatch'));
assert(!codes({segments:square,dimensions:[{...dimension,value:1,unit:'m'}]}).includes('dimension-scale-mismatch'));
assert(codes({segments:square,dimensions:[{...dimension,unitStatus:'inferred'}]}).includes('dimension-unit-unverified'));
assert(codes({segments:square,calibration:{...scale,status:'provisional'}}).includes('scale-provisional'));
assert(codes({segments:square,dimensions:[{...dimension,unit:'J'}]}).includes('unsupported-dimension-unit'));
assert(codes({segments:square,dimensions:[{...dimension,value:0}]}).includes('invalid-dimension'));
assert.equal(G.validate({segments:square,calibration:null,dimensions:[dimension]}).dimensionAudit[0].measured,null);
console.log('PASS: dimension comparison, metric conversion, provisional scale, inferred units, unsupported area units and invalid spans.');

assert(codes({segments:square,dimensions:[{...dimension,unit:'constructor'}]}).includes('unsupported-dimension-unit'));
assert(codes({segments:square,dimensions:[{...dimension,a:[0,0,1]}]}).includes('invalid-dimension'));
