import assert from 'node:assert/strict';
import '../src/layer-items.js';
const L=globalThis.LayerItems;
const order=['a','b','c','d','e'];
assert.deepEqual(L.select(['a'],'c',order,'a',{range:true}).refs,['a','b','c']);
assert.deepEqual(L.select(['e'],'c',order,'a',{range:true,toggle:true}).refs,['e','a','b','c']);
assert.deepEqual(L.select(['a','c'],'e',order,'c',{toggle:true}).refs,['a','c','e']);
assert.deepEqual(L.select(['a','c'],'a',order,'c',{toggle:true}).refs,['c']);
assert.deepEqual(L.select(['a','c'],'d',order,'c',{}).refs,['d']);
L.validate({'item:a':{locked:true,hidden:false}});
assert.throws(()=>L.validate({'item:a':{locked:'yes'}}));
assert.throws(()=>L.validate({'item:a':{unexpected:true}}));
const state={items:[{id:'a',x:0,y:0}],comments:[],photos:[],original:null,objectSettings:{'item:a':{locked:true}}};
const restored=JSON.parse(JSON.stringify(state));L.assertLocks(state,restored);
restored.objectSettings['item:a'].hidden=true;L.assertLocks(state,restored);
restored.items[0].x=1;assert.throws(()=>L.assertLocks(state,restored));
restored.items=[];assert.throws(()=>L.assertLocks(state,restored));
assert.deepEqual(L.flags({},'constructor'),{});
console.log('PASS: range/disjoint/toggle selection, private settings round trip, lock enforcement and settings validation.');
