import assert from 'node:assert/strict';
import fs from 'node:fs';
import '../src/review-history.js';
const R=globalThis.ReviewHistory;
const state={revision:'v8',comments:[{id:'sample-1',status:'open'},{id:'sample-2',status:'open'}]};
const changes=[{id:'synthetic-wall',before:'M0 0L10 0',after:'M0 0L20 0'}];
const entry=R.recordChange(state,'architecture','Extend synthetic wall',['sample-1'],changes);
R.resolveComments(state,['sample-1'],entry);
assert.equal(entry.revision,'v9');
assert.equal(state.comments[0].status,'done');
assert.equal(state.comments[1].status,'open');
assert.equal(state.comments[0].resolution.changeId,entry.id);
changes[0].after='mutated';
assert.equal(entry.changes[0].after,'M0 0L20 0');
assert.throws(()=>R.resolveComments(state,['sample-2'],entry));
assert.throws(()=>R.recordChange(state,'architecture','',['sample-1']));
assert.throws(()=>R.recordChange(state,'architecture','Unknown',['missing']));
const restored=JSON.parse(JSON.stringify(state));
assert.equal(restored.comments[0].history[0].revision,'v9');
assert.equal(restored.changeLog[0].changes[0].before,'M0 0L10 0');
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.match(html,/<button type="button" id="cancel-comment"/,'Cancel must bypass required textarea validation');
assert.match(html,/<textarea id="comment-text"[^>]* required/,'Save still validates empty text');
console.log('PASS: comment resolution linkage, revision isolation, immutable change details, import round trip and cancellation contract.');
